BEGIN;
ALTER TABLE users ADD COLUMN is_blocked boolean NOT NULL DEFAULT false;
ALTER TABLE users ADD COLUMN block_reason text NOT NULL DEFAULT '';
ALTER TABLE projects ADD COLUMN recruitment_open boolean NOT NULL DEFAULT true;
ALTER TABLE projects ADD COLUMN team_contact varchar(500) NOT NULL DEFAULT '';
ALTER TABLE projects DROP CONSTRAINT projects_status_check;
-- Legacy closed projects were explicitly closed by their owners. Keep them private
-- until reviewed; the old schema cannot tell whether they were ever approved.
UPDATE projects SET recruitment_open=false, status='pending' WHERE status='closed';
ALTER TABLE projects ADD CONSTRAINT projects_status_check CHECK(status IN ('pending','published','rejected','hidden'));
ALTER TABLE applications DROP CONSTRAINT applications_status_check;
ALTER TABLE applications ADD CONSTRAINT applications_status_check CHECK(status IN ('pending','accepted','rejected','withdrawn','left','removed'));
CREATE TABLE reports (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 reporter_id integer NOT NULL REFERENCES users(id),
 project_id integer REFERENCES projects(id),
 user_id integer REFERENCES users(id),
 reason varchar(40) NOT NULL CHECK(reason IN ('spam','abuse','fraud','other')),
 message text NOT NULL DEFAULT '',
 status varchar(20) NOT NULL DEFAULT 'pending' CHECK(status IN ('pending','resolved')),
 resolution text NOT NULL DEFAULT '',
 created_at integer NOT NULL,
 resolved_at integer,
 CHECK ((project_id IS NOT NULL) <> (user_id IS NOT NULL))
);
CREATE INDEX reports_reporter ON reports(reporter_id);
CREATE INDEX reports_status ON reports(status);
CREATE UNIQUE INDEX reports_pending_project ON reports(reporter_id,project_id) WHERE status='pending' AND project_id IS NOT NULL;
CREATE UNIQUE INDEX reports_pending_user ON reports(reporter_id,user_id) WHERE status='pending' AND user_id IS NOT NULL;
CREATE TABLE moderation_events (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 moderator_id integer NOT NULL REFERENCES users(id),
 project_id integer REFERENCES projects(id),
 user_id integer REFERENCES users(id),
 report_id integer REFERENCES reports(id),
 action varchar(40) NOT NULL,
 note text NOT NULL,
 created_at integer NOT NULL
);
COMMIT;
