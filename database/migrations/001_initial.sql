BEGIN;
CREATE TABLE users (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 email varchar(254) NOT NULL UNIQUE,
 password_hash text NOT NULL,
 name varchar(100) NOT NULL,
 bio text NOT NULL DEFAULT '',
 institute varchar(100) NOT NULL DEFAULT '',
 skills text NOT NULL DEFAULT '[]',
 role varchar(20) NOT NULL DEFAULT 'student' CHECK(role IN ('student','moderator'))
);
CREATE TABLE sessions (
 token_hash varchar(64) PRIMARY KEY,
 user_id integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 expires_at integer NOT NULL
);
CREATE INDEX sessions_expiry ON sessions(expires_at);
CREATE TABLE projects (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 owner_id integer NOT NULL REFERENCES users(id),
 title varchar(160) NOT NULL,
 description text NOT NULL,
 category varchar(60) NOT NULL CHECK(category IN ('IT','Инженерия','Наука','Социальные проекты','Дизайн')),
 format varchar(20) NOT NULL CHECK(format IN ('Онлайн','Очно','Гибрид')),
 skills text NOT NULL DEFAULT '[]',
 status varchar(20) NOT NULL DEFAULT 'pending' CHECK(status IN ('pending','published','rejected','closed')),
 moderation_note text NOT NULL DEFAULT '',
 is_demo boolean NOT NULL DEFAULT false
);
CREATE INDEX projects_status ON projects(status);
CREATE TABLE vacancies (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 project_id integer NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
 title varchar(100) NOT NULL,
 requirements text NOT NULL,
 capacity integer NOT NULL CHECK(capacity > 0 AND capacity <= 30)
);
CREATE INDEX vacancies_project ON vacancies(project_id);
CREATE TABLE applications (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 vacancy_id integer NOT NULL REFERENCES vacancies(id),
 user_id integer NOT NULL REFERENCES users(id),
 message text NOT NULL,
 status varchar(20) NOT NULL DEFAULT 'pending' CHECK(status IN ('pending','accepted','rejected')),
 UNIQUE(user_id,vacancy_id)
);
CREATE INDEX applications_vacancy_status ON applications(vacancy_id,status);
CREATE INDEX applications_user ON applications(user_id);
COMMIT;
